#!/bin/sh
set -eu

SECRETS_DIR="${KAFKA_SECRETS_DIR:-/vault/secrets/kafka}"
TLS_DIR="${KAFKA_TLS_DIR:-/tls}"
PASSWORD_FILE="$SECRETS_DIR/kafka_connect_sasl_password"

i=0
until [ -s "$PASSWORD_FILE" ] && [ -s "$TLS_DIR/ca.crt" ] && [ -s "$TLS_DIR/client.pem" ]; do
    i=$((i + 1))
    if [ "$i" -ge 60 ]; then
        echo "Timed out waiting for Kafka Connect security material" >&2
        exit 1
    fi
    sleep 1
done

KAFKA_CONNECT_PASSWORD="$(tr -d '\r\n' < "$PASSWORD_FILE")"
JAAS_CONFIG="org.apache.kafka.common.security.scram.ScramLoginModule required username=\"kafka-connect\" password=\"${KAFKA_CONNECT_PASSWORD}\";"

export CONNECT_SECURITY_PROTOCOL="SASL_SSL"
export CONNECT_SASL_MECHANISM="SCRAM-SHA-512"
export CONNECT_SASL_JAAS_CONFIG="$JAAS_CONFIG"
export CONNECT_SSL_KEYSTORE_TYPE="PEM"
export CONNECT_SSL_KEYSTORE_LOCATION="$TLS_DIR/client.pem"
export CONNECT_SSL_TRUSTSTORE_TYPE="PEM"
export CONNECT_SSL_TRUSTSTORE_LOCATION="$TLS_DIR/ca.crt"
export CONNECT_SSL_ENDPOINT_IDENTIFICATION_ALGORITHM="https"

export CONNECT_PRODUCER_SECURITY_PROTOCOL="$CONNECT_SECURITY_PROTOCOL"
export CONNECT_PRODUCER_SASL_MECHANISM="$CONNECT_SASL_MECHANISM"
export CONNECT_PRODUCER_SASL_JAAS_CONFIG="$CONNECT_SASL_JAAS_CONFIG"
export CONNECT_PRODUCER_SSL_KEYSTORE_TYPE="$CONNECT_SSL_KEYSTORE_TYPE"
export CONNECT_PRODUCER_SSL_KEYSTORE_LOCATION="$CONNECT_SSL_KEYSTORE_LOCATION"
export CONNECT_PRODUCER_SSL_TRUSTSTORE_TYPE="$CONNECT_SSL_TRUSTSTORE_TYPE"
export CONNECT_PRODUCER_SSL_TRUSTSTORE_LOCATION="$CONNECT_SSL_TRUSTSTORE_LOCATION"
export CONNECT_PRODUCER_SSL_ENDPOINT_IDENTIFICATION_ALGORITHM="$CONNECT_SSL_ENDPOINT_IDENTIFICATION_ALGORITHM"

export CONNECT_CONSUMER_SECURITY_PROTOCOL="$CONNECT_SECURITY_PROTOCOL"
export CONNECT_CONSUMER_SASL_MECHANISM="$CONNECT_SASL_MECHANISM"
export CONNECT_CONSUMER_SASL_JAAS_CONFIG="$CONNECT_SASL_JAAS_CONFIG"
export CONNECT_CONSUMER_SSL_KEYSTORE_TYPE="$CONNECT_SSL_KEYSTORE_TYPE"
export CONNECT_CONSUMER_SSL_KEYSTORE_LOCATION="$CONNECT_SSL_KEYSTORE_LOCATION"
export CONNECT_CONSUMER_SSL_TRUSTSTORE_TYPE="$CONNECT_SSL_TRUSTSTORE_TYPE"
export CONNECT_CONSUMER_SSL_TRUSTSTORE_LOCATION="$CONNECT_SSL_TRUSTSTORE_LOCATION"
export CONNECT_CONSUMER_SSL_ENDPOINT_IDENTIFICATION_ALGORITHM="$CONNECT_SSL_ENDPOINT_IDENTIFICATION_ALGORITHM"

exec /docker-entrypoint.sh start
